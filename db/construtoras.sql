-- A padrão não pode ser alterada nem apagada: é para ela que apontam os imóveis sem construtora.
CREATE OR REPLACE FUNCTION construtora_padrao_fixa() RETURNS trigger LANGUAGE plpgsql AS $f$
BEGIN
  IF OLD.padrao THEN RAISE EXCEPTION 'A construtora padrão não pode ser alterada nem excluída.'; END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $f$;
DROP TRIGGER IF EXISTS construtora_padrao_fixa ON construtoras;
CREATE TRIGGER construtora_padrao_fixa BEFORE UPDATE OR DELETE ON construtoras
  FOR EACH ROW EXECUTE FUNCTION construtora_padrao_fixa();

